/**
 * Prepares the languages that are switched on (src/i18n/locales.ts, `live: true`). Runs before every start, typecheck and build.
 *   1. src/app/<lang>/...   one tiny route file per page that re-exports the English page, so /es/merge-pdf renders the same screen in Spanish.
 *   2. public/i18n/<lang>.js  the catalog as a script that sets window.__I18N before the app starts, so a localized page is translated at first paint.
 * Both are generated and git-ignored. A language that is not live gets no routes at all, so its pages cannot be built or crawled by accident.
 * Usage: tsx scripts/gen-i18n.ts
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'fs';
import { join } from 'path';
import { DEFAULT_LANG, LOCALES } from '../src/i18n/locales';

const root = join(__dirname, '..');
const app = join(root, 'src', 'app');
const pub = join(root, 'public', 'i18n');

// the pages that exist in English: every route file in src/app except the layout and the not-found page
const skip = new Set(['_layout.tsx', '+not-found.tsx']);
const top = readdirSync(app).filter((f) => f.endsWith('.tsx') && !skip.has(f));
const guides = readdirSync(join(app, 'guides')).filter((f) => f.endsWith('.tsx'));

const reexport = (rel: string, name: string, withParams: boolean) => `// Generated by scripts/gen-i18n.ts. Do not edit.\nexport { default${withParams ? ', generateStaticParams' : ''} } from '${rel}/${name.replace(/\.tsx$/, '')}';\n`;

rmSync(pub, { recursive: true, force: true });
let live = 0;
for (const l of LOCALES) {
  if (l.code === DEFAULT_LANG) continue;
  const dir = join(app, l.code);
  rmSync(dir, { recursive: true, force: true });
  if (!l.live) continue;
  const file = join(root, 'src', 'i18n', 'catalogs', `${l.code}.json`);
  if (!existsSync(file)) throw new Error(`${l.code} is live but ${file} does not exist`);
  live++;
  mkdirSync(join(dir, 'guides'), { recursive: true });
  for (const f of top) writeFileSync(join(dir, f), reexport('..', f, f.startsWith('[')));
  for (const f of guides) writeFileSync(join(dir, 'guides', f), reexport('../..', 'guides/' + f, f.startsWith('[')));
  mkdirSync(pub, { recursive: true });
  const json = JSON.stringify(JSON.parse(readFileSync(file, 'utf8')));
  writeFileSync(join(pub, `${l.code}.js`), `window.__I18N=window.__I18N||{};window.__I18N[${JSON.stringify(l.code)}]=${json};\n`);
}
console.log(`[gen-i18n] ${live} language(s) live besides English`);
